#include "theme.h"

#include <cstdio>

static std::string Hex(uint32_t rgb)
{
    char text[8];
    snprintf(text, sizeof text, "#%06x", (unsigned)(rgb & 0xffffff));
    return text;
}

/* `amount` percent of the way from a to b. */
static uint32_t Mix(uint32_t a, uint32_t b, int amount)
{
    uint32_t out = 0;
    for (int shift = 0; shift <= 16; shift += 8) {
        int x = (int)((a >> shift) & 0xff), y = (int)((b >> shift) & 0xff);
        out |= (uint32_t)(x + (y - x) * amount / 100) << shift;
    }
    return out;
}

/* Windows has no colours for "under the pointer" and "pressed"; its own
 * controls tint the surface towards the selection colour, so do the same. */
static uint32_t Hover(const ClassicColors &c) { return Mix(c.window, c.selection, 10); }
static uint32_t Pressed(const ClassicColors &c) { return Mix(c.window, c.selection, 20); }

std::string Gtk3Colors(const ClassicColors &c)
{
    struct { const char *name; uint32_t value; } all[] = {
        { "xnt_window", c.window }, { "xnt_window_text", c.windowText },
        { "xnt_face", c.face }, { "xnt_face_text", c.faceText },
        { "xnt_shadow", c.shadow }, { "xnt_dark_shadow", c.darkShadow }, { "xnt_light", c.light },
        { "xnt_selection", c.selection }, { "xnt_selection_text", c.selectionText },
        { "xnt_menu", c.menu }, { "xnt_menu_text", c.menuText },
        { "xnt_tooltip", c.tooltip }, { "xnt_tooltip_text", c.tooltipText },
        { "xnt_gray_text", c.grayText }, { "xnt_link", c.link }, { "xnt_caption_text", c.captionText },
        { "xnt_hover", Hover(c) }, { "xnt_pressed", Pressed(c) },
    };
    std::string out = "/* Generated by xntsrv-appearance from the Windows colours. Do not edit. */\n";
    for (const auto &colour : all)
        out += std::string("@define-color ") + colour.name + " " + Hex(colour.value) + ";\n";
    return out;
}

std::string Gtk2Colors(const ClassicColors &c)
{
    struct { const char *name; uint32_t value; } all[] = {
        { "bg_color", c.face }, { "fg_color", c.faceText },
        { "base_color", c.window }, { "text_color", c.windowText },
        { "selected_bg_color", c.selection }, { "selected_fg_color", c.selectionText },
        { "menu_color", c.menu }, { "menu_fg_color", c.menuText },
        { "tooltip_bg_color", c.tooltip }, { "tooltip_fg_color", c.tooltipText },
        { "insensitive_fg_color", c.grayText }, { "link_color", c.link },
        { "hover_color", Hover(c) }, { "pressed_color", Pressed(c) },
    };
    std::string out = "# Generated by xntsrv-appearance from the Windows colours. Do not edit.\ngtk-color-scheme = \"";
    bool first = true;
    for (const auto &colour : all) {
        out += std::string(first ? "" : "\\n") + colour.name + ":" + Hex(colour.value);
        first = false;
    }
    return out + "\"\n";
}
